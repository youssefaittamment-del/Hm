    fun getDuasByCategory(categoryId: String): List<DuaItem> {
        return duas.filter { it.categoryId == categoryId }
    }

    fun getCategoryById(id: String): DuaCategory? {
        return categories.find { it.id == id }
    }

    fun searchDuas(query: String): List<DuaItem> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return duas
        return duas.filter {
            it.title.contains(q) ||
            it.arabicText.contains(q) ||
            it.categoryName.contains(q) ||
            it.virtue.contains(q) ||
            it.reference.contains(q)
        }
    }

    fun searchCategories(query: String): List<DuaCategory> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return categories
        return categories.filter {
            it.name.contains(q) ||
            it.englishName.lowercase().contains(q) ||
            it.description.contains(q)
        }
    }
